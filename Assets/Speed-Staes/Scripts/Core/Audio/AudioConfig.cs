using System;
using System.Collections.Generic;
using UnityEngine;

namespace SpeedStars.Core.Audio
{
    /// <summary>One sound effect: which clip and how loud. An empty clip means "silent" (nothing is played, nothing breaks).</summary>
    [Serializable]
    public sealed class SfxCue
    {
        [Tooltip("Which sound this entry is.")]
        [SerializeField] private SfxId id;

        [Tooltip("The clip to play. Empty = this sound is silent.")]
        [SerializeField] private AudioClip clip;

        [Tooltip("Loudness of this sound (0-1), before the system volume.")]
        [Range(0f, 1f)]
        [SerializeField] private float volume = 1f;

        public SfxId Id => id;
        public AudioClip Clip => clip;
        public float Volume => Mathf.Clamp01(volume);
    }

    /// <summary>
    /// Every number of the sound and haptic system in one asset (Data/Config/AudioConfig, T-052). The field defaults are what
    /// AudioConfigSeed writes once; at runtime the asset counts. Clips are placeholders generated by scripts/sfx-uret.py.
    /// </summary>
    [CreateAssetMenu(fileName = "AudioConfig", menuName = "Speed Stars/Config/Audio")]
    public sealed class AudioConfig : ScriptableObject
    {
        [Header("Sound effects")]
        [Tooltip("Sound id to clip and loudness. A missing id is silent.")]
        [SerializeField] private List<SfxCue> cues = new List<SfxCue>();

        [Tooltip("The same sound is not played again within this many seconds (0 = no limit; the same frame is always once).")]
        [Min(0f)]
        [SerializeField] private float minRepeatSeconds = 0.05f;

        [Header("Music")]
        [Tooltip("The looping music clip. Empty = no music (silent).")]
        [SerializeField] private AudioClip musicClip;

        [Tooltip("Music loudness (0-1).")]
        [Range(0f, 1f)]
        [SerializeField] private float musicVolume = 0.5f;

        [Header("Haptics")]
        [Tooltip("Length of the light buzz (milliseconds). 0 = no buzz.")]
        [Min(0)]
        [SerializeField] private int hapticMilliseconds = 15;

        [Tooltip("Strength of the buzz (1-255) on Android 8+; older phones buzz at their own strength.")]
        [Range(1, 255)]
        [SerializeField] private int hapticAmplitude = 80;

        [Tooltip("Shortest time between two buzzes (seconds), so fast tapping does not turn into a continuous vibration.")]
        [Min(0f)]
        [SerializeField] private float hapticMinIntervalSeconds = 0.06f;

        public float MinRepeatSeconds => minRepeatSeconds;
        public AudioClip MusicClip => musicClip;
        public float MusicVolume => Mathf.Clamp01(musicVolume);
        public int HapticMilliseconds => hapticMilliseconds;
        public int HapticAmplitude => Mathf.Clamp(hapticAmplitude, 1, 255);
        public float HapticMinIntervalSeconds => hapticMinIntervalSeconds;

        /// <summary>The entry of an id; false when the id has no entry.</summary>
        public bool TryGetCue(SfxId id, out SfxCue cue)
        {
            if (cues != null)
            {
                for (int i = 0; i < cues.Count; i++)
                {
                    if (cues[i] != null && cues[i].Id == id)
                    {
                        cue = cues[i];
                        return true;
                    }
                }
            }
            cue = null;
            return false;
        }
    }
}
